CREATE TABLE IF NOT EXISTS `kb_library` (
    `id` BIGINT NOT NULL COMMENT '知识库id',
    `library_key` VARCHAR(64) NOT NULL COMMENT '知识库稳定标识',
    `name` VARCHAR(100) NOT NULL COMMENT '知识库名称',
    `description` VARCHAR(1000) NULL COMMENT '知识库说明',
    `status` TINYINT NOT NULL DEFAULT 1 COMMENT '状态：0禁用，1启用',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `creater` BIGINT NOT NULL DEFAULT 0 COMMENT '创建人',
    `updater` BIGINT NOT NULL DEFAULT 0 COMMENT '更新人',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0否，1是',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_library_key` (`library_key`),
    KEY `idx_library_status` (`status`, `deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='AIGC知识库';

CREATE TABLE IF NOT EXISTS `kb_document` (
    `id` BIGINT NOT NULL COMMENT '文档id',
    `library_id` BIGINT NOT NULL COMMENT '知识库id',
    `document_name` VARCHAR(200) NOT NULL COMMENT '文档名称',
    `original_file_name` VARCHAR(255) NOT NULL COMMENT '上传时原始文件名',
    `file_type` VARCHAR(20) NOT NULL COMMENT '文件类型：PDF、DOCX、MD、TXT',
    `content_type` VARCHAR(100) NULL COMMENT '文件MIME类型',
    `storage_key` VARCHAR(512) NOT NULL COMMENT 'OSS对象Key',
    `file_size` BIGINT NOT NULL COMMENT '文件大小，单位字节',
    `file_hash` CHAR(64) NOT NULL COMMENT '文件SHA-256',
    `version` INT NOT NULL DEFAULT 1 COMMENT '当前文档版本',
    `status` TINYINT NOT NULL DEFAULT 0 COMMENT '状态：0已上传，1处理中，2已建索引，3处理失败',
    `current_task_id` BIGINT NULL COMMENT '当前处理任务id',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `creater` BIGINT NOT NULL DEFAULT 0 COMMENT '创建人',
    `updater` BIGINT NOT NULL DEFAULT 0 COMMENT '更新人',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0否，1是',
    PRIMARY KEY (`id`),
    KEY `idx_document_library` (`library_id`, `deleted`),
    KEY `idx_document_status` (`status`, `update_time`),
    KEY `idx_document_hash` (`library_id`, `file_hash`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='AIGC知识库文档';

CREATE TABLE IF NOT EXISTS `kb_task` (
    `id` BIGINT NOT NULL COMMENT '任务id',
    `library_id` BIGINT NOT NULL COMMENT '知识库id',
    `document_id` BIGINT NOT NULL COMMENT '文档id',
    `document_version` INT NOT NULL COMMENT '任务对应的文档版本',
    `source_storage_key` VARCHAR(512) NOT NULL COMMENT '任务对应的OSS对象Key快照',
    `task_type` TINYINT NOT NULL COMMENT '任务类型：1文档建索引',
    `status` TINYINT NOT NULL DEFAULT 0 COMMENT '状态：0待处理，1处理中，2等待重试，3索引完成，4处理失败',
    `retry_count` INT NOT NULL DEFAULT 0 COMMENT '已重试次数',
    `max_retries` INT NOT NULL DEFAULT 3 COMMENT '最大重试次数',
    `message_id` VARCHAR(64) NULL COMMENT 'RabbitMQ消息id',
    `total_chunks` INT NOT NULL DEFAULT 0 COMMENT '分块总数',
    `processed_chunks` INT NOT NULL DEFAULT 0 COMMENT '已处理分块数',
    `failed_chunks` INT NOT NULL DEFAULT 0 COMMENT '失败分块数',
    `error_code` VARCHAR(64) NULL COMMENT '错误码',
    `error_message` VARCHAR(1000) NULL COMMENT '脱敏后的错误信息',
    `sent_at` DATETIME NULL COMMENT '消息成功投递时间',
    `started_at` DATETIME NULL COMMENT '开始处理时间',
    `finished_at` DATETIME NULL COMMENT '处理结束时间',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `creater` BIGINT NOT NULL DEFAULT 0 COMMENT '创建人',
    `updater` BIGINT NOT NULL DEFAULT 0 COMMENT '更新人',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_document_version_task` (`document_id`, `document_version`, `task_type`),
    UNIQUE KEY `uk_task_message_id` (`message_id`),
    KEY `idx_task_status` (`status`, `update_time`),
    KEY `idx_task_library` (`library_id`, `create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='AIGC文档异步处理任务';
